// The token radar's model, version radar-2: one snapshot of the protocol universe in,
// one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and
// adds pre-token protocols below the watchlist floor: the early rows the radar exists to
// find. A protocol is pre-token when its index entry records no token (no market cap, no
// CoinGecko id, no symbol); the snapshot's live-token protocols are kept apart and shown as
// the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures. The starter's flat 0.25x
// multiple is replaced by a multiple the snapshot itself supplies: for each category, the
// median market-cap/TVL of the tokenized protocols in that category, winsorized to
// [0.02, 1.50]; a category with fewer than three tokenized peers falls back to the global
// median across all tokenized protocols. Two honest caveats, stated on the dashboard:
// market cap is circulating value, not fully-diluted value, so these multiples are a
// conservative proxy and the implied values read as lower-bound style estimates; and a
// protocol "records no token", never "has no token", because its DefiLlama record may
// simply not carry one.
//
//   multiple   = median(mcap_usd / tvl_usd) of tokenized peers in the category (n >= 3),
//                else the global median; winsorized to [0.02, 1.50]
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.02 x min(chains - 1, 5)            (multi-chain reach, max 1.10)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// Confidence (0..100) scores how much of the model a row's own record supports: age
// known, 7-day change reported, enough category comps, several chains, TVL at or above
// the floor. The value band widens as confidence falls:
//
//   spread = 0.15 + 0.50 x (1 - confidence / 100)
//   band   = [implied x (1 - spread), implied x (1 + spread)]
//
// No protocol name is ever special-cased: the same function scores every row.

